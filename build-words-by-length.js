const fs = require('fs');
const text = fs.readFileSync('words_alpha.txt', 'utf8');
const lines = text.split(/\r?\n/);
const out = { 3: [], 4: [], 6: [], 7: [], 8: [] };

for (const line of lines) {
    const s = line.trim().toLowerCase();
    if (!/^[a-z]+$/.test(s)) continue;
    const L = s.length;
    if (out[L]) out[L].push(s);
}

for (const k of Object.keys(out)) out[k].sort();

const allWords = [
    ...out[3],
    ...out[4],
    ...out[6],
    ...out[7],
    ...out[8]
];

const chunks = [];
chunks.push('// Auto-generated by build-words-by-length.js for 3, 4, 6, 7, and 8-letter word finder pages.');
chunks.push(`const wordList = [${allWords.map(w => `'${w}'`).join(',')}];`);

fs.writeFileSync('words-by-length.js', chunks.join('\n'));

console.log('Wrote words-by-length.js (Total:', allWords.length, 'words)');
for (const L of [3, 4, 6, 7, 8]) console.log(`  ${L}-letter: ${out[L].length}`);

