const fs = require('fs');
const text = fs.readFileSync('words_alpha.txt', 'utf8');
const lines = text.split(/\r?\n/);
const out = { 3: [], 4: [], 6: [], 7: [], 8: [] };

for (const line of lines) {
    const s = line.trim().toLowerCase();
    if (!/^[a-z]+$/.test(s)) continue;
    const L = s.length;
    if (out[L]) out[L].push(s);
}

for (const k of Object.keys(out)) out[k].sort();

const chunks = [];
chunks.push('// Auto-generated by build-words-by-length.js — a–z only. Five-letter games use words.js.');
chunks.push('window.WORD_LISTS_BY_LENGTH = {');

for (const L of [3, 4, 6, 7, 8]) {
    const arr = out[L];
    const formatted = arr.map(w => `'${w}'`).join(',');
    chunks.push(`  ${L}: [${formatted}],`);
}
chunks.push('};');
fs.writeFileSync('words-by-length.js', chunks.join('\n'));

console.log('Wrote words-by-length.js');
for (const L of [3, 4, 6, 7, 8]) console.log(`  ${L}: ${out[L].length}`);
