# Phase 1.5 Rollback Script
# Restoration of native browser rendering stability

Get-ChildItem -Filter *.html | ForEach-Object {
    $file = $_.FullName
    Write-Host "Rolling back $file"
    $content = [System.IO.File]::ReadAllText($file)
    
    # 1. CSS Loading Rollback
    $content = $content -replace '<link rel="stylesheet" href="style.css" media="print" onload="this.media=''all''">', '<link rel="stylesheet" href="style.css">'
    $content = $content -replace '<noscript><link rel="stylesheet" href="style.css"></noscript>', ''
    
    # 2. Font Loading Rollback
    # Match the media/onload pattern for fonts
    $content = [regex]::Replace($content, '<link rel="stylesheet" href="https://fonts.googleapis.com/css2\?family=[^"]+media="print" onload="this.media=''all''">', {
        param($m)
        $url = [regex]::Match($m.Value, 'href="([^"]+)"').Groups[1].Value
        return "<link rel=`"stylesheet`" href=`"$url`">"
    })
    # Remove preload as well if it's there
    $content = [regex]::Replace($content, '<link rel="preload" href="https://fonts.googleapis.com/css2\?family=[^"]+as="style">', "")
    
    # 3. Font Display block -> swap
    $content = $content -replace "display=block", "display=swap"
    
    # 4. Remove Static Skeleton
    $content = [regex]::Replace($content, "(?s)<div class=`"results-list`" id=`"resultsList`".*?<\/div>", "<div class=`"results-list`" id=`"resultsList`">`n                        <!-- Results generated by JS -->`n                    </div>")

    # 5. Remove any leftover .hydrated or .loaded classes if they were hardcoded (unlikely but safe)
    $content = $content -replace ' class="hydrated"', ''
    $content = $content -replace ' class="loaded"', ''

    [System.IO.File]::WriteAllText($file, $content, [System.Text.Encoding]::UTF8)
}

Write-Host "Rollback complete."
